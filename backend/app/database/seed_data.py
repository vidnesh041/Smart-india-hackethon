def seed_database(force_reseed: bool = True):
    """Initializes tables and seeds all live authentic government schemes."""
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()
    try:
        count = db.query(Scheme).count()
        if count < len(AUTHENTIC_LIVE_SCHEMES) or force_reseed:
            db.query(Scheme).delete()
            for s_data in AUTHENTIC_LIVE_SCHEMES:
                scheme = Scheme(**s_data)
                db.add(scheme)
            db.commit()
            print(f"Successfully seeded all {len(AUTHENTIC_LIVE_SCHEMES)} live authentic government schemes into database.")
        else:
            print(f"Database already contains {count} live schemes.")
    except Exception as e:
        db.rollback()
        print(f"Error seeding database: {e}")
    finally:
        db.close()

if __name__ == "__main__":
    seed_database(force_reseed=True)
